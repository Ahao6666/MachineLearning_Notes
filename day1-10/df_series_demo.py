# 第二部分：DataFrame —— 一个表格
# ============================================================================
print("\n" + "=" * 60)
print("📘 第二部分：DataFrame — 一个表格")
print("=" * 60)


# ---------------------------------------------------------------------------
# 2.1 DataFrame 是什么
# ---------------------------------------------------------------------------
print("\n--- 2.1 DataFrame 是什么 ---")
#
# DataFrame = 多个 Series 组成的二维表格
#
# 生活中的类比：
#   一个 DataFrame 就像 Excel 中的一个工作表
#   行 = 一条记录（一个学生）
#   列 = 一个字段（姓名/年龄/成绩）
#
#        姓名    年龄    成绩    城市        ← 列名（columns）
#   0    张三    20     85     北京      ← 行索引（index）
#   1    李四    21     92     上海
#   2    王五    19     78     广州
#

df = pd.DataFrame({
    "姓名": ["张三", "李四", "王五", "赵六"],
    "年龄": [20, 21, 19, 22],
    "成绩": [85, 92, 78, 90],
    "城市": ["北京", "上海", "广州", "深圳"],
})
print("一个简单的 DataFrame:")
print(df)
print(f"\n  类型:    {type(df)}")
print(f"  形状:    {df.shape}")       # (4, 4)  ← 4行4列
print(f"  行数:    {len(df)}")        # 4
print(f"  列数:    {len(df.columns)}") # 4
print(f"  列名:    {list(df.columns)}")
print(f"  行索引:  {list(df.index)}")


# ---------------------------------------------------------------------------
# 2.2 DataFrame 的本质 —— 列是 Series
# ---------------------------------------------------------------------------
print("\n--- 2.2 DataFrame 的本质：列 = Series ---")
#
# DataFrame 的每一列都是一个 Series
#

print("取出 '姓名' 列:")
print(df["姓名"])
print(f"  类型: {type(df['姓名'])}")  # pandas.core.series.Series

print("\n取出 '成绩' 列:")
print(df["成绩"])
print(f"  平均值: {df['成绩'].mean()}")
print(f"  最大值: {df['成绩'].max()}")

# 可以同时取出多列（返回 DataFrame）
print("\n取出多列（姓名 + 成绩）:")
print(df[["姓名", "成绩"]])


# ---------------------------------------------------------------------------
# 2.3 创建 DataFrame 的多种方式
# ---------------------------------------------------------------------------
print("\n--- 2.3 创建 DataFrame 的多种方式 ---")

# 方式 1：从字典创建（最常用）
df1 = pd.DataFrame({
    "A": [1, 2, 3],
    "B": [4, 5, 6],
})
print("方式1 - 从字典:")
print(df1)

# 方式 2：从列表嵌套字典（每行一个字典）
df2 = pd.DataFrame([
    {"姓名": "张三", "年龄": 20},
    {"姓名": "李四", "年龄": 21},
    {"姓名": "王五", "年龄": 19},
])
print("\n方式2 - 从列表嵌套字典:")
print(df2)

# 方式 3：从 NumPy 数组 + 指定列名
df3 = pd.DataFrame(
    np.random.randn(3, 4),  # 3行4列的随机数
    columns=["A", "B", "C", "D"]
)
print("\n方式3 - 从 NumPy 数组:")
print(df3.round(2))

# 方式 4：从 CSV 文件（最实用）
# df = pd.read_csv("data.csv")


# ---------------------------------------------------------------------------
# 2.4 行列访问 —— iloc vs loc
# ---------------------------------------------------------------------------
print("\n--- 2.4 行列访问：iloc vs loc ---")
#
# 这是初学者最容易搞混的地方，记住这个口诀：
#
#   iloc = index location  = 按「位置」访问（第几行第几列）
#   loc  = label location  = 按「标签」访问（行名和列名）
#
#      类似于：
#        iloc → 数组下标  arr[0, 1]
#        loc  → 字典键值  dict["key"]
#

df = pd.DataFrame({
    "姓名": ["张三", "李四", "王五", "赵六"],
    "年龄": [20, 21, 19, 22],
    "成绩": [85, 92, 78, 90],
}, index=["S1", "S2", "S3", "S4"])  # 自定义行索引

print("数据:")
print(df)

print("\n【iloc — 按位置编号访问】")
print(f"  iloc[0]      → 第 0 行（第一行）:\n{df.iloc[0]}")
print(f"  iloc[0, 1]   → 第 0 行第 1 列（年龄）: {df.iloc[0, 1]}")
print(f"  iloc[0:2]    → 第 0~1 行:\n{df.iloc[0:2]}")
print(f"  iloc[:, 1]   → 第 1 列（所有行的年龄列）:\n{df.iloc[:, 1]}")

print("\n【loc — 按标签名访问】")
print(f"  loc['S1']    → 行索引为 S1 的行:\n{df.loc['S1']}")
print(f"  loc['S1', '年龄'] → S1 行的年龄列: {df.loc['S1', '年龄']}")
print(f"  loc['S1':'S3']    → S1 到 S3 的行:\n{df.loc['S1':'S3']}")
print(f"  loc[:, '姓名':'年龄'] → 姓名到年龄列:\n{df.loc[:, '姓名':'年龄']}")

# 快速记忆表：
#
#   写法             含义                   类比
#   ──────────────── ───────────────────    ──────────────
#   df["成绩"]       选取一列（返回 Series）    df.成绩
#   df[["姓名","成绩"]] 选取多列（返回 DataFrame）
#   df.iloc[0]       第 0 行                 列表[0]
#   df.iloc[0:3]     第 0~2 行               列表[0:3]
#   df.loc["S1"]     行名为 S1 的行           字典["S1"]
#   df.loc["S1":"S3"] 行名 S1~S3（包含结尾）
#   df.iloc[0, 1]    第 0 行第 1 列           二维数组[0][1]
#   df.loc["S1", "年龄"] S1 行的年龄列          表格查值


