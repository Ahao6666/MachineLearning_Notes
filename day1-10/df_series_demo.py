import numpy as np

# ============================================================================
# 第一部分：Series —— 一列数据
# ============================================================================
print("=" * 60)
print("📗 第一部分：Series — 一列数据")
print("=" * 60)


# ---------------------------------------------------------------------------
# 1.1 Series 是什么
# ---------------------------------------------------------------------------
print("\n--- 1.1 Series 是什么 ---")
#
# Series = 带标签的一维数组
#
# 生活中的类比：
#   一个 Series 就像 Excel 中的「一列」
#   或者像一张纸条，上面依次写着：
#     第1行: 张三
#     第2行: 李四
#     第3行: 王五
#   每个值都有一个对应的「行号」（索引）
#

# 创建 Series 的最简方式
s = pd.Series([85, 92, 78, 90])
print("最简单的 Series:")
print(s)
print(f"  类型:    {type(s)}")
print(f"  值:      {s.values}")     # 纯数值数组 [85 92 78 90]
print(f"  索引:    {s.index}")      # RangeIndex(start=0, stop=4, step=1)
print(f"  形状:    {s.shape}")      # (4,)


# ---------------------------------------------------------------------------
# 1.2 自定义索引
# ---------------------------------------------------------------------------
print("\n--- 1.2 自定义索引 ---")
#
# 默认索引是 0, 1, 2, ...，但可以改成有意义的标签
#

# 带自定义索引的 Series
s_named = pd.Series(
    [85, 92, 78, 90],
    index=["张三", "李四", "王五", "赵六"],
    name="期末考试成绩"
)

print("带自定义索引的 Series:")
print(s_named)
print(f"\n  索引: {list(s_named.index)}")

# 通过索引名访问（类似字典）
print(f"  张三的成绩: {s_named['张三']}")
print(f"  李四的成绩: {s_named['李四']}")

# 通过位置访问（类似列表）
print(f"  第 0 个: {s_named.iloc[0]}")
print(f"  第 -1 个（最后一个）: {s_named.iloc[-1]}")


# ---------------------------------------------------------------------------
# 1.3 Series 的常见创建方式
# ---------------------------------------------------------------------------
print("\n--- 1.3 Series 的常见创建方式 ---")

# 从列表创建
s1 = pd.Series([1, 2, 3])
print(f"从列表:   {s1.values}")

# 从字典创建（键→索引, 值→数据）
s2 = pd.Series({"张三": 85, "李四": 92, "王五": 78})
print(f"从字典:   {s2.values}")
print(f"  索引: {list(s2.index)}")

# 从标量创建（所有行共用同一个值）
s3 = pd.Series(0, index=range(5))
print(f"从标量:   {s3.values}")

# 从 NumPy 数组创建
s4 = pd.Series(np.array([1.5, 2.5, 3.5]))
print(f"从NumPy:  {s4.values}")


# ---------------------------------------------------------------------------
# 1.4 Series 的常用操作
# ---------------------------------------------------------------------------
print("\n--- 1.4 Series 的常用操作 ---")

scores = pd.Series([85, 92, 78, 90, 88], index=["A", "B", "C", "D", "E"])

# 运算（向量化，和 NumPy 一样）
print(f"原始:          {scores.values}")
print(f"全部 +5:       {(scores + 5).values}")
print(f"全部 ×1.1:     {(scores * 1.1).values}")
print(f"大于 85 的:    {(scores > 85).values}")  # 返回布尔 Series

# 筛选
print(f"\n成绩 > 85 的:")
print(scores[scores > 85])

# 统计方法
print(f"\n统计信息:")
print(f"  总和:     {scores.sum()}")
print(f"  平均值:   {scores.mean():.1f}")
print(f"  最大值:   {scores.max()}")
print(f"  最小值:   {scores.min()}")
print(f"  标准差:   {scores.std():.1f}")
print(f"  中位数:   {scores.median()}")


