# ---------------------------------------------------------------------------
# 3.1 索引是什么
# ---------------------------------------------------------------------------
print("\n--- 3.1 索引是什么 ---")
#
# 索引（Index）是 Pandas 最强大的概念之一。
# 它就像 Excel 最左边的「行号」，但功能更强。
#
# 索引的特点：
#   1. 唯一标识每一行
#   2. 可以通过索引快速定位数据
#   3. 对齐操作时按索引匹配
#   4. 可以是数字、字符串、日期等
#

s1 = pd.Series([1, 2, 3], index=["a", "b", "c"])
s2 = pd.Series([10, 20, 30], index=["b", "c", "d"])

print("s1:")
print(s1)
print("\ns2:")
print(s2)

# 按索引对齐相加（Pandas 自动匹配相同索引的值）
print("\ns1 + s2（按索引对齐）:")
print(s1 + s2)
# a: s1有,s2无 → NaN
# b: s1有,s2有 → 1+10=11
# c: s1有,s2有 → 2+20=22
# d: s1无,s2有 → NaN
#
# 这就是索引的威力 —— 不需要关心顺序，Pandas 自动按索引匹配！


# ---------------------------------------------------------------------------
# 3.2 设置与重置索引
# ---------------------------------------------------------------------------
print("\n--- 3.2 设置与重置索引 ---")

df = pd.DataFrame({
    "学生ID": ["S001", "S002", "S003"],
    "姓名": ["张三", "李四", "王五"],
    "成绩": [85, 92, 78],
})
print("原始数据:")
print(df)

# 将某列设为索引
df_indexed = df.set_index("学生ID")
print("\n将 '学生ID' 设为索引后:")
print(df_indexed)
print(f"  现在可以通过 ID 直接查:")
print(f"  df_indexed.loc['S002']:\n{df_indexed.loc['S002']}")

# 重置索引（把索引变回普通列）
df_reset = df_indexed.reset_index()
print("\n重置索引后:")
print(df_reset)


# ---------------------------------------------------------------------------
# 3.3 重新索引（reindex）
# ---------------------------------------------------------------------------
print("\n--- 3.3 重新索引（reindex）---")
#
# reindex 可以改变 Series/DataFrame 的顺序和索引
#

s = pd.Series([85, 92, 78], index=["A", "B", "C"])
print(f"原始: {s.values}")
print(f"索引: {list(s.index)}")

# 按新索引重新排列
s_reindexed = s.reindex(["C", "A", "B", "D"])
print(f"\nreindex(['C','A','B','D']) 后:")
print(s_reindexed)
# "D" 原来没有 → NaN（可以用 fill_value 填充）


